import { jsPDF } from "jspdf";
import type { AgentResult, CaseStrength } from "@/lib/openrouter";
import { Button } from "@/components/ui/button";
import { Printer } from "lucide-react";

interface CaseSummaryReportProps {
  results: AgentResult[];
  caseStrength: CaseStrength | null;
  userProblem: string;
}

function cleanText(text: string | undefined | null): string {
  if (!text) return '';
  return text
    .replace(/\*\*/g, '')
    .replace(/\*/g, '')
    .replace(/###/g, '')
    .replace(/##/g, '')
    .replace(/#/g, '')
    .replace(/language_detected:\s*\w+/gi, '')
    .replace(/^\s*[\-\•]\s*/gm, '')
    .replace(/```[\s\S]*?```/g, '')
    .replace(/`/g, '')
    .trim();
}

function extractLaws(researchText: string) {
  const lines = researchText.split("\n").filter((l) => l.trim());
  const laws: { act: string; description: string }[] = [];
  for (const line of lines) {
    const match = line.match(/(?:Section\s+[\d\w]+.*?(?:of|,)\s+)?(.+?(?:Act|Code|Rules|Bill|Ordinance).+?\d{4})/i);
    if (match) {
      laws.push({ act: cleanText(match[1]), description: cleanText(line) });
    }
  }
  return laws.length > 0 ? laws.slice(0, 5) : [{ act: "Applicable Laws", description: cleanText(researchText.slice(0, 200)) }];
}

function extractSteps(drafterText: string) {
  const steps: string[] = [];
  const lines = drafterText.split("\n");
  for (const line of lines) {
    const match = line.match(/^\s*(?:\d+[\.\)]\s*|[-*•]\s*)/);
    if (match) {
      const cleaned = cleanText(line.replace(/^\s*(?:\d+[\.\)]\s*|[-*•]\s*)/, ""));
      if (cleaned.length > 5 && cleaned.length < 120) steps.push(cleaned);
    }
  }
  return steps.slice(0, 6);
}

function extractSchemes(schemeText: string) {
  const schemes: { name: string; description: string }[] = [];
  const lines = schemeText.split("\n").filter((l) => l.trim().length > 5);
  let currentName = "";
  let currentDesc = "";

  for (const line of lines) {
    const cleaned = cleanText(line);
    if (!cleaned) continue;
    // Detect scheme name lines (bold or numbered headings)
    if (cleaned.length < 80 && (line.match(/^\s*\d+[\.\)]/) || line.match(/^\s*[-•]/) || line.match(/^[A-Z]/) || line.match(/Scheme|Yojana|Programme|Mission|Portal/i))) {
      if (currentName && currentDesc) {
        schemes.push({ name: currentName, description: currentDesc.trim() });
      }
      currentName = cleaned;
      currentDesc = "";
    } else if (currentName) {
      currentDesc += (currentDesc ? " " : "") + cleaned;
    }
  }
  if (currentName) {
    schemes.push({ name: currentName, description: (currentDesc || "").trim() });
  }
  return schemes.slice(0, 5);
}

const CaseSummaryReport = ({ results, caseStrength, userProblem }: CaseSummaryReportProps) => {
  const researchResult = results.find((r) => r.agent === "research");
  const drafterResult = results.find((r) => r.agent === "drafter");
  const schemeResult = results.find((r) => r.agent === "scheme");

  const laws = researchResult ? extractLaws(researchResult.response) : [];
  const steps = drafterResult ? extractSteps(drafterResult.response) : [];
  const schemes = schemeResult ? extractSchemes(schemeResult.response) : [];

  const score = caseStrength?.overall_score ?? 50;
  const urgencyScore = caseStrength?.winning_probability ?? 50;

  const handleGeneratePDF = () => {
    const doc = new jsPDF();
    const pageWidth = doc.internal.pageSize.getWidth();
    const pageHeight = doc.internal.pageSize.getHeight();
    const margin = 20;
    const contentWidth = pageWidth - margin * 2;
    let y = 20;

    const reportId = Math.floor(100000 + Math.random() * 900000);

    function checkNewPage() {
      if (y > pageHeight - 30) {
        doc.addPage();
        y = 20;
        addFooter();
      }
    }

    function addFooter() {
      doc.setFontSize(8);
      doc.setTextColor(150, 150, 150);
      doc.text(
        "Generated by NyayMitra AI | For informational purposes only | Free Legal Aid: NALSA 1516 | nalsa.gov.in",
        margin,
        pageHeight - 10,
        { maxWidth: contentWidth }
      );
    }

    // HEADER BACKGROUND
    doc.setFillColor(26, 60, 94);
    doc.rect(0, 0, pageWidth, 35, "F");

    // HEADER TEXT
    doc.setFontSize(20);
    doc.setTextColor(255, 255, 255);
    doc.setFont("helvetica", "bold");
    doc.text("Nyay Bandhu - Legal Rights Report", margin, 15);

    doc.setFontSize(10);
    doc.setFont("helvetica", "normal");
    doc.text("Your Free AI Legal Friend | nalsa.gov.in | Helpline: 1516", margin, 25);

    // DATE AND REPORT ID
    doc.setFontSize(9);
    doc.setTextColor(200, 200, 200);
    doc.text("Date: " + new Date().toLocaleDateString("en-IN") + "   |   Report ID: NB-" + reportId, margin, 32);

    y = 45;

    // ORANGE DIVIDER LINE
    doc.setDrawColor(249, 115, 22);
    doc.setLineWidth(1);
    doc.line(margin, y, pageWidth - margin, y);
    y += 10;

    // SECTION 1 — USER PROBLEM
    const problemText = cleanText(userProblem
      ? userProblem.substring(0, 300) + (userProblem.length > 300 ? "..." : "")
      : "Not provided");
    const problemLines = doc.splitTextToSize(problemText, contentWidth - 10);
    const problemBoxHeight = Math.max(30, problemLines.length * 6 + 12);

    doc.setFillColor(240, 244, 255);
    doc.roundedRect(margin, y, contentWidth, problemBoxHeight, 3, 3, "F");
    doc.setFontSize(11);
    doc.setTextColor(26, 60, 94);
    doc.setFont("helvetica", "bold");
    doc.text("Your Situation:", margin + 5, y + 8);

    doc.setFontSize(10);
    doc.setFont("helvetica", "normal");
    doc.setTextColor(30, 41, 59);
    doc.text(problemLines, margin + 5, y + 16);
    y += problemBoxHeight + 10;
    checkNewPage();

    // SECTION 2 — CASE STRENGTH
    doc.setFontSize(13);
    doc.setTextColor(26, 60, 94);
    doc.setFont("helvetica", "bold");
    doc.text("Case Strength", margin, y);
    y += 7;

    const strength = score;
    doc.setFillColor(230, 230, 230);
    doc.roundedRect(margin, y, contentWidth, 8, 2, 2, "F");

    const strengthColor: [number, number, number] =
      strength >= 70 ? [22, 163, 74] : strength >= 40 ? [234, 179, 8] : [239, 68, 68];
    doc.setFillColor(...strengthColor);
    doc.roundedRect(margin, y, (contentWidth * strength) / 100, 8, 2, 2, "F");

    doc.setFontSize(9);
    doc.setTextColor(255, 255, 255);
    doc.text(strength + "%", margin + (contentWidth * strength) / 100 - 15, y + 5.5);
    y += 18;
    checkNewPage();

    // SECTION 3 — APPLICABLE LAWS
    doc.setFontSize(13);
    doc.setTextColor(26, 60, 94);
    doc.setFont("helvetica", "bold");
    doc.text("Laws That Protect You", margin, y);
    y += 7;

    if (laws.length > 0) {
      laws.forEach((law) => {
        checkNewPage();
        const descText = cleanText(law.description);
        const descLines = doc.splitTextToSize(descText, contentWidth - 10);
        const boxH = Math.max(22, descLines.length * 5 + 14);

        doc.setFillColor(248, 250, 255);
        doc.roundedRect(margin, y, contentWidth, boxH, 2, 2, "F");
        doc.setDrawColor(249, 115, 22);
        doc.setLineWidth(0.5);
        doc.line(margin, y, margin, y + boxH);

        doc.setFontSize(10);
        doc.setFont("helvetica", "bold");
        doc.setTextColor(26, 60, 94);
        doc.text(cleanText(law.act).slice(0, 60), margin + 5, y + 7);

        doc.setFontSize(9);
        doc.setFont("helvetica", "normal");
        doc.setTextColor(71, 85, 105);
        doc.text(descLines, margin + 5, y + 14);
        y += boxH + 4;
      });
    }
    y += 10;
    checkNewPage();

    // SECTION 4 — LEGAL SUMMARY (Your Rights Explained)
    const summaryText = cleanText(caseStrength?.summary || "");
    if (summaryText) {
      doc.setFontSize(13);
      doc.setTextColor(26, 60, 94);
      doc.setFont("helvetica", "bold");
      doc.text("Your Rights Explained", margin, y);
      y += 7;

      doc.setFontSize(10);
      doc.setFont("helvetica", "normal");
      doc.setTextColor(30, 41, 59);
      const summaryLines = doc.splitTextToSize(summaryText, contentWidth);
      summaryLines.forEach((line: string) => {
        checkNewPage();
        doc.text(line, margin, y);
        y += 6;
      });
      y += 10;
      checkNewPage();
    }

    // SECTION 5 — ACTION PLAN (from next_steps only)
    if (steps.length > 0) {
      doc.setFontSize(13);
      doc.setTextColor(26, 60, 94);
      doc.setFont("helvetica", "bold");
      doc.text("Your Action Plan", margin, y);
      y += 7;

      steps.forEach((step, index) => {
        checkNewPage();
        doc.setFillColor(249, 115, 22);
        doc.circle(margin + 4, y + 2, 3, "F");

        doc.setFontSize(9);
        doc.setTextColor(255, 255, 255);
        doc.text((index + 1).toString(), margin + 2.5, y + 3.5);

        doc.setFontSize(10);
        doc.setFont("helvetica", "normal");
        doc.setTextColor(30, 41, 59);
        const stepText = cleanText(step);
        const stepLines = doc.splitTextToSize(stepText, contentWidth - 15);
        doc.text(stepLines, margin + 12, y + 4);
        y += stepLines.length * 6 + 5;
      });
      y += 10;
      checkNewPage();
    }

    // SECTION 6 — LAWYER URGENCY
    doc.setFontSize(13);
    doc.setTextColor(26, 60, 94);
    doc.setFont("helvetica", "bold");
    doc.text("Do You Need a Lawyer?", margin, y);
    y += 7;

    const lawyerColor: [number, number, number] =
      urgencyScore >= 70 ? [239, 68, 68] : urgencyScore >= 40 ? [234, 179, 8] : [22, 163, 74];
    const lawyerMsg =
      urgencyScore >= 70
        ? "We Strongly Recommend a Lawyer"
        : urgencyScore >= 40
          ? "Consider Getting Legal Guidance"
          : "You Can Likely Handle This Yourself";

    doc.setFillColor(...lawyerColor);
    doc.roundedRect(margin, y, contentWidth, 8, 2, 2, "F");

    doc.setFontSize(10);
    doc.setTextColor(255, 255, 255);
    doc.setFont("helvetica", "bold");
    doc.text(cleanText(lawyerMsg) + " (" + urgencyScore + "%)", margin + 5, y + 5.5);
    y += 18;
    checkNewPage();

    // SECTION 7 — FREE LEGAL AID BOX
    doc.setFillColor(26, 60, 94);
    doc.roundedRect(margin, y, contentWidth, 28, 3, 3, "F");

    doc.setFontSize(12);
    doc.setTextColor(249, 115, 22);
    doc.setFont("helvetica", "bold");
    doc.text("Free Legal Aid Available", margin + 5, y + 8);

    doc.setFontSize(11);
    doc.setTextColor(255, 255, 255);
    doc.setFont("helvetica", "bold");
    doc.text("NALSA Helpline: 1516 (Free, All India)", margin + 5, y + 16);

    doc.setFontSize(9);
    doc.setFont("helvetica", "normal");
    doc.text("Visit your nearest District Legal Services Authority (DLSA) | nalsa.gov.in", margin + 5, y + 23);
    y += 38;

    // SECTION 8 — GOVERNMENT SCHEMES
    if (schemes.length > 0) {
      checkNewPage();
      doc.setFontSize(13);
      doc.setTextColor(26, 60, 94);
      doc.setFont("helvetica", "bold");
      doc.text("Government Schemes & Resources", margin, y);
      y += 7;

      schemes.forEach((scheme) => {
        checkNewPage();
        const nameText = cleanText(scheme.name);
        const descText = cleanText(scheme.description);

        doc.setFontSize(10);
        doc.setFont("helvetica", "bold");
        doc.setTextColor(26, 60, 94);
        doc.text(nameText.slice(0, 70), margin, y);
        y += 5;

        if (descText) {
          doc.setFontSize(9);
          doc.setFont("helvetica", "normal");
          doc.setTextColor(71, 85, 105);
          const dLines = doc.splitTextToSize(descText.slice(0, 200), contentWidth);
          doc.text(dLines, margin, y);
          y += dLines.length * 5 + 4;
        }
      });
    }

    // FOOTER
    addFooter();

    // SAVE
    doc.save("NyayBandhu-Legal-Report-NB" + reportId + ".pdf");
  };

  return (
    <Button onClick={handleGeneratePDF} className="bg-accent text-accent-foreground hover:bg-accent/90 gap-2">
      <Printer className="w-4 h-4" /> Generate Case Summary Report
    </Button>
  );
};

export default CaseSummaryReport;
